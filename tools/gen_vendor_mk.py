#!/usr/bin/env python3
"""Generate Android.mk / pandora-vendor.mk / BoardConfigVendor.mk for a blob package.

Usage:
    gen_vendor_mk.py <device_vendor_dir>

Reads <device_vendor_dir>/proprietary-files.txt (LineageOS format, '-' = strip)
and emits:
    Android.mk
    pandora-vendor.mk
    BoardConfigVendor.mk

Module names are derived from the full path so they are unique; the installed
filename is restored through LOCAL_INSTALLED_MODULE_STEM.
"""

import os
import re
import sys

PART_PREFIX = {
    "vendor": ("$(TARGET_OUT_VENDOR)", "LOCAL_VENDOR_MODULE := true"),
    "odm": ("$(TARGET_OUT_ODM)", "LOCAL_ODM_MODULE := true"),
    "system_ext": ("$(TARGET_OUT_SYSTEM_EXT)", "LOCAL_SYSTEM_EXT_MODULE := true"),
}


def sanitize(s):
    return re.sub(r"[^A-Za-z0-9_]", "_", s)


def classify(name):
    low = name.lower()
    if low.endswith(".so"):
        return "SHARED_LIBRARIES"
    if low.endswith(".apk"):
        return "APPS"
    if low.endswith(".jar"):
        return "JAVA_LIBRARIES"
    if low.endswith((".bin", ".mbn", ".elf", ".mdt", ".b00", ".b01", ".fw")):
        return "ETC"
    return None  # decided by caller via ELF sniff


def is_elf(path):
    try:
        with open(path, "rb") as f:
            return f.read(4) == b"\x7fELF"
    except OSError:
        return False


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    base = sys.argv[1]
    list_path = os.path.join(base, "proprietary-files.txt")
    entries = [l.strip() for l in open(list_path) if l.strip() and not l.startswith("#")]

    mods = []
    for entry in entries:
        raw = entry.lstrip("-")
        parts = raw.split("/")
        if len(parts) < 3 or parts[0] not in PART_PREFIX:
            continue
        part, rel = parts[0], "/".join(parts[1:])
        src = os.path.join(base, "proprietary", part, rel)
        if not os.path.isfile(src):
            continue  # symlink placeholder or missing

        out_root, part_flag = PART_PREFIX[part]
        fname = os.path.basename(rel)
        subdir = os.path.dirname(rel)

        cls = classify(fname)
        if cls is None:
            cls = "EXECUTABLES" if is_elf(src) else "ETC"

        module = sanitize("blob_%s_%s" % (part, rel))
        lines = [
            "include $(CLEAR_VARS)",
            "LOCAL_MODULE := %s" % module,
            "LOCAL_MODULE_OWNER := xiaomi",
            "LOCAL_SRC_FILES := proprietary/%s/%s" % (part, rel),
            "LOCAL_MODULE_TAGS := optional",
            "LOCAL_MODULE_CLASS := %s" % cls,
            "LOCAL_INSTALLED_MODULE_STEM := %s" % fname,
            "LOCAL_MODULE_PATH := %s/%s" % (out_root, subdir) if subdir else
            "LOCAL_MODULE_PATH := %s" % out_root,
            part_flag,
        ]
        if cls == "SHARED_LIBRARIES":
            lines.insert(5, "LOCAL_MODULE_SUFFIX := .so")
            lines.insert(6, "LOCAL_MULTILIB := %s" % ("64" if rel.startswith("lib64") else "32"))
            lines.insert(7, "LOCAL_CHECK_ELF_FILES := false")
            lines.insert(8, "LOCAL_MODULE_STEM := %s" % fname[:-3])
        elif cls == "APPS":
            lines.insert(5, "LOCAL_CERTIFICATE := PRESIGNED")
            lines.insert(6, "LOCAL_DEX_PREOPT := false")
            lines.insert(7, "LOCAL_MODULE_SUFFIX := .apk")
            lines.insert(8, "LOCAL_MODULE_STEM := %s" % fname[:-4])
        elif cls == "JAVA_LIBRARIES":
            lines.insert(5, "LOCAL_MODULE_SUFFIX := .jar")
            lines.insert(6, "LOCAL_MODULE_STEM := %s" % fname[:-4])
        lines.append("include $(BUILD_PREBUILT)")
        lines.append("")
        mods.append((module, lines))

    with open(os.path.join(base, "Android.mk"), "w") as f:
        f.write("# Auto-generated by tools/gen_vendor_mk.py -- NOT build-verified.\n")
        f.write("# Regenerate with the official extract-files.py on a live device when possible.\n\n")
        f.write("LOCAL_PATH := $(call my-dir)\n\n")
        for _m, lines in mods:
            f.write("\n".join(lines))
            f.write("\n")

    with open(os.path.join(base, "pandora-vendor.mk"), "w") as f:
        f.write("# Auto-generated by tools/gen_vendor_mk.py\n\n")
        f.write("PRODUCT_SOONG_NAMESPACES += vendor/xiaomi/pandora\n\n")
        f.write("PRODUCT_PACKAGES += \\\n")
        for i, (m, _l) in enumerate(mods):
            sep = " \\" if i < len(mods) - 1 else ""
            f.write("    %s%s\n" % (m, sep))

    with open(os.path.join(base, "BoardConfigVendor.mk"), "w") as f:
        f.write("# Auto-generated by tools/gen_vendor_mk.py\n")
        f.write("BOARD_VENDOR_SEPOLICY_DIRS += vendor/xiaomi/pandora/sepolicy/vendor\n")

    print("modules=%d" % len(mods))
    print("wrote Android.mk, pandora-vendor.mk, BoardConfigVendor.mk")


if __name__ == "__main__":
    main()
